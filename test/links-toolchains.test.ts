// Local links against the real toolchains: a cargo, a cmake and an npm consumer in the root build
// against the member's job worktree through `forge run`, and leave both worktrees clean. Each test
// skips when its tool is not on PATH; CI's Ubuntu and macOS runners have all three.
import { after, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { twoRepo } from './job-repos-fixture.ts';
import type { TwoRepo } from './job-repos-fixture.ts';
import { hasBinary } from '../lib/core/os/process.ts';

const cleanups: (() => void)[] = [];
after(() => cleanups.forEach((c) => c()));

const skip = (tool: string) => (hasBinary(tool) ? false : `${tool} is not on PATH`);

/**
 * The two-repo project with `rootFiles` and `libFiles` on both repos' main (pushed), the root
 * component `app` linked to lib's `engine` at `enginePath`, and the job's worktrees created.
 */
async function project(opts: { rootFiles: Record<string, string>; libFiles: Record<string, string>; enginePath: string; link: Record<string, unknown>; commands: Record<string, string> }) {
  const p: TwoRepo = await twoRepo();
  cleanups.push(p.cleanup);
  p.commit(p.root, opts.rootFiles, 'app sources');
  p.commit(p.lib, opts.libFiles, 'engine sources');
  p.git(p.root, 'push', '-q', 'origin', 'main');
  p.git(p.lib, 'push', '-q', 'origin', 'main');
  p.config((c) => {
    Object.assign(c.commands, opts.commands);
    c.components = [
      { name: 'app', path: '.', kind: 'app', dependsOn: [{ component: 'engine', type: 'build', link: opts.link }] },
      { name: 'engine', repo: 'lib', path: opts.enginePath, kind: 'library' },
    ];
  });
  const j = await p.f('job', 'new', '--title', `toolchain ${Math.random().toString(36).slice(2, 8)}`);
  await p.f('job', 'repo', 'add', j.id, 'lib');
  const created = await p.f('worktree', 'create', j.id);
  const scratch = path.join(p.parent, 'scratch');
  fs.mkdirSync(scratch);
  return { p, id: j.id, rootWt: created.path as string, libWt: created.repos[0].path as string, scratch };
}

const clean = (p: TwoRepo, ...wts: string[]) => {
  for (const wt of wts) assert.equal(p.git(wt, 'status', '--porcelain', '--untracked-files=all'), '', wt);
};

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "engine-core",
]

[[package]]
name = "engine-core"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${'0'.repeat(64)}"
`;

describe('links: real toolchains', { concurrency: 3 }, () => {
  test('cargo consumer builds against the job worktree', { skip: skip('cargo') }, async () => {
    const x = await project({
      rootFiles: {
        'Cargo.toml': '[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\nengine-core = "0.1"\n',
        'src/main.rs': 'fn main() {\n    println!("marker={}", engine_core::marker());\n}\n',
        'Cargo.lock': CARGO_LOCK,
      },
      libFiles: {
        'engine-core/Cargo.toml': '[package]\nname = "engine-core"\nversion = "0.1.0"\nedition = "2021"\n',
        'engine-core/src/lib.rs': 'pub fn marker() -> &\'static str {\n    "released"\n}\n',
      },
      enginePath: 'engine-core',
      link: { ecosystem: 'cargo', name: 'engine-core' },
      commands: { build: 'cargo build --offline -q', run: 'cargo run --offline -q' },
    });
    x.p.commit(x.libWt, { 'engine-core/src/lib.rs': 'pub fn marker() -> &\'static str {\n    "job-worktree"\n}\n' }, 'marker');
    const env = { CARGO_HOME: path.join(x.scratch, 'cargo-home'), CARGO_TARGET_DIR: path.join(x.scratch, 'target') };
    const build = await x.p.raw(['run', x.id, 'build'], env);
    const out = JSON.parse(build.stdout);
    assert.equal(out.ok, true, out.tail);
    assert.deepEqual(out.links, ['cargo:engine-core']);
    assert.deepEqual(out.restored, ['Cargo.lock'], 'the [patch] rewrote the lockfile, and Forge wrote it back');
    const ran = JSON.parse((await x.p.raw(['run', x.id, 'run'], env)).stdout);
    assert.equal(ran.ok, true, ran.tail);
    assert.match(ran.tail, /marker=job-worktree/);
    clean(x.p, x.rootWt, x.libWt);
    assert.equal(fs.readFileSync(path.join(x.rootWt, 'Cargo.lock'), 'utf8'), CARGO_LOCK);
  });

  test('cmake consumer configures against the job worktree', { skip: skip('cmake') }, async () => {
    const x = await project({
      rootFiles: {
        '.gitignore': 'build/\n',
        'CMakeLists.txt': [
          'cmake_minimum_required(VERSION 3.14)',
          'project(app NONE)',
          'include(FetchContent)',
          'FetchContent_Declare(engine GIT_REPOSITORY https://example.invalid/engine.git)',
          'FetchContent_MakeAvailable(engine)',
          'message(STATUS "engine_SOURCE_DIR=${engine_SOURCE_DIR}")',
          '',
        ].join('\n'),
      },
      libFiles: { 'cpp/engine.txt': 'engine\n' },
      enginePath: 'cpp',
      link: { ecosystem: 'cmake', name: 'engine' },
      commands: { configure: 'cmake -S . -B build' },
    });
    const out = JSON.parse((await x.p.raw(['run', x.id, 'configure'])).stdout);
    assert.equal(out.ok, true, out.tail);
    assert.deepEqual(out.links, ['cmake:engine']);
    assert.ok(out.tail.includes(`engine_SOURCE_DIR=${path.join(x.libWt, 'cpp')}`), out.tail);
    clean(x.p, x.rootWt, x.libWt);
  });

  test('npm consumer installs the job worktree', { skip: skip('npm') }, async () => {
    const pkg = '{\n  "name": "app",\n  "version": "1.0.0",\n  "private": true\n}\n';
    const lock = JSON.stringify({ name: 'app', version: '1.0.0', lockfileVersion: 3, requires: true, packages: { '': { name: 'app', version: '1.0.0' } } }, null, 2) + '\n';
    const x = await project({
      rootFiles: { '.gitignore': 'node_modules/\n', 'package.json': pkg, 'package-lock.json': lock },
      libFiles: { 'js/package.json': '{\n  "name": "engine",\n  "version": "1.0.0"\n}\n', 'js/index.js': 'module.exports = "engine";\n' },
      enginePath: 'js',
      link: { ecosystem: 'npm', name: 'engine' },
      commands: { install: 'npm install --offline --no-audit --no-fund' },
    });
    const env = { npm_config_cache: path.join(x.scratch, 'npm-cache'), npm_config_update_notifier: 'false' };
    const out = JSON.parse((await x.p.raw(['run', x.id, 'install'], env)).stdout);
    assert.equal(out.ok, true, out.tail);
    assert.deepEqual(out.links, ['npm:engine']);
    const link = path.join(x.rootWt, 'node_modules', 'engine');
    assert.equal(fs.lstatSync(link).isSymbolicLink(), true);
    assert.equal(fs.realpathSync(link), fs.realpathSync(path.join(x.libWt, 'js')));
    assert.equal(fs.readFileSync(path.join(x.rootWt, 'package.json'), 'utf8'), pkg);
    assert.equal(fs.readFileSync(path.join(x.rootWt, 'package-lock.json'), 'utf8'), lock);
    clean(x.p, x.rootWt, x.libWt);
  });
});
